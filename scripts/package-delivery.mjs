// scripts/package-delivery.mjs — Aegis release packer (AEG-19).
//
// The working tree is ~845 MB because it carries reproducible build caches
// (video-tool/node_modules/.cache, .remotion, out/, Playwright copies). Those are
// NOT deliverables. This script builds a deterministic, content-addressed archive
// of the SHIPPING surface only and verifies it byte-for-byte on the next run.
//
// Zero dependencies: node: built-ins only. Tar writing and gzip are implemented
// here instead of shelling out to `tar`, so the archive is reproducible across
// macOS / Linux and no host toolchain is assumed.
//
//   node scripts/package-delivery.mjs             # build dist/*.tar.gz + MANIFEST.json
//   node scripts/package-delivery.mjs --verify    # re-verify archive + manifest
//   node scripts/package-delivery.mjs --list      # show what would be packed
//
// This script NEVER deletes anything from the working tree.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const MANIFEST_PATH = path.join(DIST, 'MANIFEST.json');

// Directories that are regenerated by a build, or are evidence/media rather than
// runtime code. `vendor/` is deliberately NOT here: pdf.js, pdf-lib, tesseract
// and tessdata are required at runtime and must travel with the product.
const EXCLUDE_DIR_NAMES = new Set([
  'node_modules', '.git', '.cache', '.remotion', 'dist', 'out',
  'artifacts', 'shots', 'assets', 'public', 'coverage', '.idea',
  '.vscode', 'tls', 'vendor-src', '_audit', '__pycache__',
]);
// NOTE: `.gz` is NOT excluded — tessdata ships `*.traineddata.gz` and the OCR
// worker needs them. Only media / archives / private key material are dropped.
const EXCLUDE_EXTS = new Set([
  '.mp4', '.mov', '.webm', '.m4a', '.wav', '.mp3',
  '.tgz', '.zip', '.7z', '.pem', '.key', '.crt', '.p12', '.pfx',
  '.pcap', '.log', '.pyc', '.DS_Store',
  // Embedded database + WAL/SHM sidecars must never ship (B-03).
  '.db', '.db-shm', '.db-wal', '.sqlite', '.sqlite3',
]);
const EXCLUDE_BASENAMES = new Set([
  '.DS_Store', 'Thumbs.db', 'pre-patch.tgz', 'pre-p3.tgz',
  'package-lock.json.bak',
]);
// B-01/B-02/B-03: the packer walks the filesystem, NOT .gitignore, so locally
// generated secrets and the development database were shipped to every customer.
// These rules are TOP-LEVEL precise: `modules/webgpu-topology/src/data/` is
// legitimate runtime code and must still ship.
const EXCLUDE_TOP_LEVEL_DIRS = new Set(['data']);
const EXCLUDE_REL_PATHS = new Set(['config/local.json']);
// Internal-only material: engineering audits, closure/brief reports, promo
// pipeline, and unpublished compliance placeholders. A customer must never
// receive these — they describe defects, pricing strategy or unfilled contacts.
const EXCLUDE_PREFIXES = [
  'docs/AUDIT-',                 // internal engineering audits
  'AEGIS_',                      // internal reports / attorney briefs at root
  // .well-known/security.txt is intentionally SHIPPED: it now carries the real
  // maintainer contact (RFC 9116) and is listed in REQUIRED below.
  'video-tool/src/',             // promo video pipeline (Remotion), not product code
  'video-tool/public/',
  'video-tool/assets/',
  'video-tool/artifacts/',
  'video-tool/out/',
  'video-tool/video-tool/',
];
const EXCLUDE_PROMO_FILES = new Set([
  'tts.mjs', 'capture.mjs', 'durations.mjs',
  // Promo-pipeline manifest (Remotion/React) — the shipped verify scripts need
  // Playwright only and carry no dependency manifest of their own.
  'package.json', 'package-lock.json',
]);
function isNeverShip(rel) {
  if (EXCLUDE_REL_PATHS.has(rel)) return true;
  if (EXCLUDE_TOP_LEVEL_DIRS.has(rel.split('/')[0])) return true;
  if (EXCLUDE_PREFIXES.some((p) => rel.startsWith(p))) return true;
  if (rel.startsWith('video-tool/')) {
    const base = rel.split('/').pop();
    if (EXCLUDE_PROMO_FILES.has(base)) return true;
    if (/^probe.*\.mjs$/.test(base)) return true; // all probe*.mjs, present and future
  }
  return false;
}
// Files a customer MUST receive. Their absence is a broken delivery, not a
// warning. vendor/MANIFEST.json is the third-party attribution index.
const REQUIRED = [
  'server.js', 'package.json', 'README.md', 'DELIVERY_REPORT.md', 'LICENSE',
  'LICENSES/Apache-2.0.txt',
  'SBOM.cdx.json', 'SECURITY.md', '.well-known/security.txt',
  'COMMERCIAL-LICENSE.md', 'EULA.md', 'PRICING.md', 'CHANGELOG.md',
  'CONTRIBUTING.md', 'CODE_OF_CONDUCT.md', 'docs/API.md', 'docs/SDK.md',
  '.gitignore', '.github/workflows/ci-runtime.yml',
  'aegis-shell/index.html', 'aegis-shell/src/app.js',
  'modules/doc-redactor/index.html',
  'modules/doc-redactor/vendor/MANIFEST.json',
  'modules/doc-redactor/vendor/tessdata/eng.traineddata.gz',
  'modules/webgpu-topology/index.html',
  'modules/sync-canvas/src/audit/HashChain.js',
  'scripts/zero-dep-lint.mjs',
  'scripts/verify-zero-deps.mjs',
  'scripts/verify-headers.mjs',
  'scripts/run-all-tests.mjs',
  'adapters/tsa-rfc3161/index.js',
  'docs/CLAIMS-WORDING.md',
  'scripts/setup.mjs',        // one-click install entrypoint — MUST ship (B-01)
  'aegis-shell/console.html', // operator console — MUST ship, never dropped (B-02)
  // Legal document set (v4) — a customer must receive the full paper trail.
  'docs/legal/LEGAL-INDEX.md',
  'docs/legal/ORDER-FORM-TEMPLATE.md',
  'docs/legal/DPA-STATEMENT.md',
  'docs/LANGUAGES.md',
];
const MAX_ARCHIVE_MB = 80;

function sha256(buf) { return crypto.createHash('sha256').update(buf).digest('hex'); }

function collect(dir, rel, acc) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, ent.name);
    const r = rel ? rel + '/' + ent.name : ent.name;
    if (ent.isSymbolicLink()) continue;                 // never ship a symlink out of ROOT
    if (isNeverShip(r)) continue;                      // B-03: no local secret / dev DB
    if (ent.isDirectory()) {
      if (EXCLUDE_DIR_NAMES.has(ent.name)) continue;
      collect(abs, r, acc);
      continue;
    }
    if (!ent.isFile()) continue;
    if (EXCLUDE_BASENAMES.has(ent.name)) continue;
    if (EXCLUDE_EXTS.has(path.extname(ent.name).toLowerCase())) continue;
    const st = fs.statSync(abs);
    acc.push({ rel: r, abs, size: st.size });
  }
}

// ---- minimal USTAR writer (deterministic: mtime 0, uid/gid 0, sorted names) ----
function writeStr(buf, s, off, len) {
  const b = Buffer.from(s, 'utf8');
  if (b.length > len) throw new Error(`tar field too long (${b.length} > ${len}): ${s}`);
  b.copy(buf, off);
}
function writeOct(buf, n, off, len) {
  const s = n.toString(8).padStart(len - 1, '0') + '\0';
  if (s.length !== len) throw new Error(`tar octal overflow: ${n}`);
  buf.write(s, off, len, 'ascii');
}
function splitUstar(name) {
  if (Buffer.byteLength(name) <= 100) return { prefix: '', name };
  const parts = name.split('/');
  let i = 0, prefix = '';
  while (i < parts.length - 1 && Buffer.byteLength(parts.slice(0, i + 1).join('/')) <= 155) {
    prefix = parts.slice(0, i + 1).join('/');
    i++;
  }
  const tail = parts.slice(i).join('/');
  if (!tail || Buffer.byteLength(tail) > 100) throw new Error('path cannot be split into USTAR: ' + name);
  return { prefix, name: tail };
}
function tarHeader(rel, size) {
  const h = Buffer.alloc(512, 0);
  const { prefix, name } = splitUstar(rel);
  writeStr(h, name, 0, 100);
  writeOct(h, 0o644, 100, 8);
  writeOct(h, 0, 108, 8);
  writeOct(h, 0, 116, 8);
  writeOct(h, size, 124, 12);
  writeOct(h, 0, 136, 12);                 // fixed epoch → reproducible
  h.fill(0x20, 148, 156);                  // checksum placeholder = spaces
  h.write('0', 156, 1, 'ascii');           // regular file
  writeStr(h, 'ustar\0', 257, 6);
  writeStr(h, '00', 263, 2);
  writeStr(h, 'aegis', 265, 32);
  writeStr(h, 'aegis', 297, 32);
  writeStr(h, prefix, 345, 155);
  let sum = 0;
  for (let i = 0; i < 512; i++) sum += h[i];
  h.write(sum.toString(8).padStart(6, '0') + '\0 ', 148, 8, 'ascii');
  return h;
}
function buildTar(files) {
  const chunks = [];
  for (const f of files) {
    const data = fs.readFileSync(f.abs);
    chunks.push(tarHeader(f.rel, data.length), data);
    const pad = (512 - (data.length % 512)) % 512;
    if (pad) chunks.push(Buffer.alloc(pad, 0));
  }
  chunks.push(Buffer.alloc(1024, 0));       // two zero blocks = end of archive
  return Buffer.concat(chunks);
}
function parseTar(buf) {
  const out = [];
  let off = 0;
  while (off + 512 <= buf.length) {
    const h = buf.subarray(off, off + 512);
    if (h.every((b) => b === 0)) break;
    const size = parseInt(h.subarray(124, 136).toString('ascii').replace(/\0.*$/, '').trim() || '0', 8);
    const prefix = h.subarray(345, 500).toString('utf8').replace(/\0.*$/, '');
    const name = h.subarray(0, 100).toString('utf8').replace(/\0.*$/, '');
    const rel = prefix ? prefix + '/' + name : name;
    const data = buf.subarray(off + 512, off + 512 + size);
    out.push({ rel, data });
    off += 512 + Math.ceil(size / 512) * 512;
  }
  return out;
}

function gzipDeterministic(buf) {
  const gz = zlib.gzipSync(buf, { level: 9 });
  // Force the gzip mtime field to zero even if a runtime ever writes a clock.
  gz.writeUInt32LE(0, 4);
  return gz;
}

function assertShipSafe(rels) {
  const bad = [];
  for (const r of rels) {
    const parts = r.split('/');
    // Two HARD assertions (B-03): the archive must contain neither the local
    // issuer secret nor any embedded database. Checked on BUILD and on VERIFY,
    // against the actual tar entries — not just against source-tree intentions.
    if (EXCLUDE_REL_PATHS.has(r)) bad.push(`${r} [B-03: local issuer secret must never ship]`);
    if (EXCLUDE_TOP_LEVEL_DIRS.has(parts[0])) bad.push(`${r} [B-03: runtime data/DB must never ship]`);
    if (/\.(db|db-shm|db-wal|sqlite|sqlite3)$/i.test(r)) bad.push(`${r} [B-03: database file]`);
    if (parts.some((p) => EXCLUDE_DIR_NAMES.has(p))) bad.push(`${r} [excluded dir]`);
    if (EXCLUDE_EXTS.has(path.extname(r).toLowerCase())) bad.push(`${r} [excluded extension]`);
    if (/(^|\/)(key|cert)\.pem$|\.key$|\.p12$|\.pfx$/i.test(r)) bad.push(`${r} [private key]`);
    if (r.includes('..') || r.startsWith('/') || path.isAbsolute(r)) bad.push(`${r} [unsafe path]`);
  }
  const missing = REQUIRED.filter((r) => !rels.includes(r));
  return { bad, missing };
}

function build() {
  const files = [];
  collect(ROOT, '', files);
  files.sort((a, b) => a.rel.localeCompare(b.rel, 'en'));
  const rels = files.map((f) => f.rel);
  const { bad, missing } = assertShipSafe(rels);
  if (bad.length || missing.length) {
    console.error('[delivery] FAIL — shipping surface is not clean:');
    for (const b of bad.slice(0, 20)) console.error('  ' + b);
    for (const m of missing) console.error('  missing required: ' + m);
    process.exit(1);
  }
  const tar = buildTar(files);
  const gz = gzipDeterministic(tar);
  const mb = gz.length / (1024 * 1024);
  if (mb > MAX_ARCHIVE_MB) {
    console.error(`[delivery] FAIL — archive is ${mb.toFixed(1)} MiB, budget is ${MAX_ARCHIVE_MB} MiB`);
    process.exit(1);
  }
  const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
  const archiveName = `aegis-delivery-${version}.tar.gz`;
  fs.mkdirSync(DIST, { recursive: true });
  fs.writeFileSync(path.join(DIST, archiveName), gz);
  const manifest = {
    schema: 'aegis-delivery-manifest/1',
    product: 'Aegis',
    version,
    archive: archiveName,
    archiveSha256: sha256(gz),
    archiveBytes: gz.length,
    payloadBytes: files.reduce((n, f) => n + f.size, 0),
    fileCount: files.length,
    excludes: {
      dirNames: [...EXCLUDE_DIR_NAMES].sort(),
      topLevelDirs: [...EXCLUDE_TOP_LEVEL_DIRS].sort(),
      relPaths: [...EXCLUDE_REL_PATHS].sort(),
      extensions: [...EXCLUDE_EXTS].sort(),
      basenames: [...EXCLUDE_BASENAMES].sort(),
    },
    required: REQUIRED,
    files: Object.fromEntries(files.map((f) => [f.rel, { bytes: f.size, sha256: sha256(fs.readFileSync(f.abs)) }])),
  };
  fs.writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2) + '\n');
  console.log(`[delivery] PASS — ${manifest.fileCount} files, ${(manifest.payloadBytes / 1048576).toFixed(1)} MiB payload → ${mb.toFixed(1)} MiB archive`);
  console.log(`[delivery] archive  dist/${archiveName}`);
  console.log(`[delivery] sha256   ${manifest.archiveSha256}`);
  console.log('[delivery] excluded node_modules/, build caches, rendered media, private key material (nothing deleted)');
}

function verify() {
  if (!fs.existsSync(MANIFEST_PATH)) {
    console.error('[delivery] FAIL — no MANIFEST.json; run without --verify first');
    process.exit(1);
  }
  const m = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
  const archive = path.join(DIST, m.archive);
  if (!fs.existsSync(archive)) {
    console.error('[delivery] FAIL — archive missing: ' + archive);
    process.exit(1);
  }
  const gz = fs.readFileSync(archive);
  if (sha256(gz) !== m.archiveSha256) {
    console.error('[delivery] FAIL — archive sha256 does not match manifest');
    process.exit(1);
  }
  const entries = parseTar(zlib.gunzipSync(gz));
  const rels = entries.map((e) => e.rel);
  const { bad, missing } = assertShipSafe(rels);
  if (bad.length || missing.length) {
    console.error('[delivery] FAIL — archive contains forbidden or missing files:');
    for (const b of bad.slice(0, 20)) console.error('  ' + b);
    for (const r of missing) console.error('  missing required: ' + r);
    process.exit(1);
  }
  if (entries.length !== m.fileCount || rels.length !== Object.keys(m.files).length) {
    console.error(`[delivery] FAIL — file count drift (archive ${entries.length}, manifest ${m.fileCount})`);
    process.exit(1);
  }
  for (const e of entries) {
    const want = m.files[e.rel];
    if (!want || want.bytes !== e.data.length || sha256(e.data) !== want.sha256) {
      console.error('[delivery] FAIL — content hash mismatch: ' + e.rel);
      process.exit(1);
    }
  }
  // Freshness: the package must not be OLDER than the source tree. The archive is
  // checked against its own manifest above (integrity), but that says nothing about
  // whether the package was built BEFORE files were added to the repo. If the source
  // shipping surface now contains files the manifest never recorded (e.g. the
  // operator console or setup script added after the build), the deliverable is
  // stale and must be rebuilt — this is the B-02 root cause (a 1-day-old package
  // silently passed verify because it only checked itself).
  const srcAcc = [];
  collect(ROOT, '', srcAcc);
  const srcFiles = srcAcc.map((f) => f.rel).sort();
  const pkgFiles = Object.keys(m.files).sort();
  const missingFromPackage = srcFiles.filter((f) => !pkgFiles.includes(f));
  if (missingFromPackage.length) {
    console.error('[delivery] FAIL — package is STALE; source has files the manifest lacks:');
    for (const f of missingFromPackage.slice(0, 20)) console.error('  + ' + f);
    process.exit(1);
  }
  const orphans = pkgFiles.filter((f) => !srcFiles.includes(f));
  if (orphans.length) console.warn('[delivery] WARN — package has orphan files absent from source: ' + orphans.slice(0, 10).join(', '));
  const mb = gz.length / 1048576;
  if (mb > MAX_ARCHIVE_MB) {
    console.error(`[delivery] FAIL — ${mb.toFixed(1)} MiB exceeds ${MAX_ARCHIVE_MB} MiB budget`);
    process.exit(1);
  }
  console.log(`[delivery] VERIFY PASS — ${entries.length} files, every sha256 matches, no caches/media/keys, ${mb.toFixed(1)} MiB`);
}

const args = process.argv.slice(2);
if (args.includes('--verify')) verify();
else if (args.includes('--list')) {
  const files = [];
  collect(ROOT, '', files);
  files.sort((a, b) => a.rel.localeCompare(b.rel, 'en'));
  for (const f of files) console.log(f.rel);
  console.error(`[delivery] ${files.length} files, ${(files.reduce((n, f) => n + f.size, 0) / 1048576).toFixed(1)} MiB payload`);
} else build();
