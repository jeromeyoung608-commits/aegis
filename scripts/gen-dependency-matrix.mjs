/**
 * Generates the dependency matrix that README §13 and docs/DEPENDENCY_AUDIT.md
 * quote. Everything is derived from the working tree, never typed by hand:
 *
 *   node scripts/gen-dependency-matrix.mjs            # print markdown
 *   node scripts/gen-dependency-matrix.mjs --write    # rewrite docs/DEPENDENCY_AUDIT.md
 *   node scripts/gen-dependency-matrix.mjs --check     # fail if the section is stale
 *
 * "Runtime dependency" here means code that ships to the browser and is not
 * first-party: vendored libraries, bare npm specifiers, or a sibling module.
 * Test-only devDependencies are reported separately.
 */
import { readdirSync, readFileSync, statSync, existsSync, writeFileSync } from 'node:fs';
import { join, relative, dirname, resolve } from 'node:path';

const ROOT = resolve(dirname(new URL(import.meta.url).pathname), '..');
const MODS = join(ROOT, 'modules');

// Test trees are excluded: they may import devDependencies (Playwright, pdf-lib)
// and never ship in the delivery package.
const isTestPath = (p) => /(^|\/)(tests?|__tests__)(\/|$)/.test(p) || /(\.test|\.spec|test-[\w-]+|-test)\.[cm]?js$/.test(p);

function walk(dir, acc = []) {
  for (const e of readdirSync(dir)) {
    if (['node_modules', 'vendor', 'dist', '.git', 'tests', 'test'].includes(e)) continue;
    const p = join(dir, e);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, acc);
    else if (/\.(js|mjs|cjs|ts)$/.test(e) && !isTestPath(p)) acc.push(p);
  }
  return acc;
}

function ports(dir) {
  const out = { bare: new Set(), siblings: new Set(), files: 0 };
  for (const f of walk(dir)) {
    out.files++;
    const src = readFileSync(f, 'utf8');
    for (const m of src.matchAll(/from\s+'([^']+)'|import\s*\(\s*'([^']+)'\s*\)/g)) {
      const spec = m[1] || m[2];
      if (!spec) continue;
      if (spec.startsWith('node:')) continue;
      if (spec.startsWith('.')) {
        const target = resolve(dirname(f), spec);
        if (target.includes(join(ROOT, 'modules')) && !target.startsWith(dir + '/')) {
          const sib = relative(join(ROOT, 'modules'), target).split('/')[0];
          out.siblings.add(sib);
        }
        continue;
      }
      out.bare.add(spec);
    }
  }
  return out;
}

function pkg(dir) {
  const p = join(dir, 'package.json');
  if (!existsSync(p)) return { deps: [], dev: [] };
  const j = JSON.parse(readFileSync(p, 'utf8'));
  return { deps: Object.keys(j.dependencies || {}), dev: Object.keys(j.devDependencies || {}) };
}

function vendor(dir) {
  const v = join(dir, 'vendor');
  if (!existsSync(v)) return null;
  const children = readdirSync(v).filter((n) => statSync(join(v, n)).isDirectory());
  let bytes = 0;
  const walkSize = (d) => { for (const e of readdirSync(d)) { const p = join(d, e); const s = statSync(p); s.isDirectory() ? walkSize(p) : (bytes += s.size); } };
  walkSize(v);
  return { children, kb: Math.round(bytes / 1024), manifest: existsSync(join(v, 'MANIFEST.json')) };
}

const rows = [];
for (const d of ['aegis-shell', ...readdirSync(MODS).sort().map((n) => 'modules/' + n)]) {
  const dir = join(ROOT, d);
  if (!existsSync(dir) || !statSync(dir).isDirectory()) continue;
  const p = ports(dir);
  const pk = pkg(dir);
  const v = vendor(dir);
  rows.push({
    dir: d.replace('modules/', ''),
    files: p.files,
    bare: [...p.bare].filter((s) => !s.startsWith('/')).sort(),
    siblings: [...p.siblings].sort(),
    dev: pk.dev,
    runtimeDeps: pk.deps,
    vendor: v,
  });
}

const clean = rows.filter((r) => !r.runtimeDeps.length && !r.vendor && !r.bare.length && !r.siblings.length);
const lines = [];
lines.push('<!-- generated by scripts/gen-dependency-matrix.mjs - do not hand-edit -->');
lines.push('| Component | Own .js files | Third-party runtime code | Cross-module imports (first-party, relative) | Dev-only deps | Verdict |');
lines.push('|---|---|---|---|---|---|');
for (const r of rows) {
  const third = r.vendor
    ? `vendored ${r.vendor.children.join(', ')} (${r.vendor.kb} KB${r.vendor.manifest ? ', MANIFEST verified' : ''})`
    : (r.runtimeDeps.length ? 'npm: ' + r.runtimeDeps.join(', ') : (r.bare.length ? 'bare imports: ' + r.bare.join(', ') : 'none'));
  const sib = r.siblings.length ? r.siblings.join(', ') : '-';
  const dev = r.dev.length ? r.dev.join(', ') : '-';
  const verdict = (!r.vendor && !r.runtimeDeps.length && !r.bare.length) ? 'zero third-party' : 'third-party present';
  lines.push(`| \`${r.dir}\` | ${r.files} | ${third} | ${sib} | ${dev} | ${verdict} |`);
}
lines.push('');
lines.push(`Totals: ${rows.length} components, ${clean.length} with zero third-party runtime code, `
  + `${rows.filter((r) => r.vendor).length} vendoring third-party libraries, `
  + `${rows.reduce((a, r) => a + r.files, 0)} first-party .js files scanned.`);
lines.push('A cross-module import is first-party code only: it is a relative path into a sibling module, never an npm package.');

const md = lines.join('\n') + '\n';
const target = join(ROOT, 'docs/DEPENDENCY_AUDIT.md');

if (process.argv.includes('--write')) {
  writeFileSync(target, `# Aegis dependency matrix\n\n${md}\n## Notes\n\n- "zero third-party" means the component ships no vendor/ directory and imports nothing outside first-party code.\n- Dev-only dependencies never ship in the delivery tarball; they exist for module test suites only.\n- Vendored libraries keep their upstream licences; attribution ships in each vendor/ directory and in NOTICE.\n- Regenerate with \`node scripts/gen-dependency-matrix.mjs --write\`; \`--check\` fails if the checked-in copy is stale.\n`);
  console.log('[dep-matrix] written', target);
} else if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (!current.includes(md.trim())) { console.error('[dep-matrix] STALE - run node scripts/gen-dependency-matrix.mjs --write'); process.exit(1); }
  console.log('[dep-matrix] PASS - dependency matrix is current');
} else {
  console.log(md);
}
