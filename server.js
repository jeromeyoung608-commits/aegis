// D1: optional global per-IP rate limit (requests / minute). Off by default
// (AEGIS_RATE_LIMIT=0). Operators fronting the service with no proxy can enable
// it; reverse proxies (deploy/reverse-proxy/nginx.conf) also provide limiting.
const RATE_LIMIT = Number(process.env.AEGIS_RATE_LIMIT || 0);
const rateBuckets = new Map();
function globalRateLimited(ip) {
  if (!RATE_LIMIT) return false;
  const now = Date.now();
  let b = rateBuckets.get(ip);
  if (!b || now - b.start > 60_000) { b = { count: 0, start: now }; rateBuckets.set(ip, b); }
  b.count++;
  return b.count > RATE_LIMIT;
}

// D2: fail-soft environment validation — warnings only, never blocks boot. Surfaces
// the most common misconfigurations (wrong auth mode, incomplete OIDC, missing
// secret in production) instead of failing obscurely at request time.
function validateEnv() {
  const mode = (CONFIG.auth && CONFIG.auth.mode) || 'local';
  if (!['local', 'oidc'].includes(mode)) {
    console.warn(`[aegis] AEGIS_AUTH_MODE="${mode}" unknown — falling back to "local".`);
  }
  if (mode === 'oidc') {
    const o = CONFIG.auth.oidc || {};
    if (!o.issuer || !o.clientId) {
      console.warn('[aegis] AEGIS_AUTH_MODE=oidc but OIDC issuer/clientId not set — OIDC login will be unavailable.');
    }
  }
  if (process.env.NODE_ENV === 'production' && !ISSUER_SECRET) {
    console.warn('[aegis] NODE_ENV=production but AEGIS_ISSUER_SECRET unset — operator console / LAN token minting locked.');
  }
  if (PORT && Number.isNaN(Number(PORT))) console.warn(`[aegis] PORT="${PORT}" is not numeric.`);
}
// Aggregate Prometheus metrics. Unauthenticated by design (standard scrape target);
// only non-secret counters are exposed.
function handleMetrics(req, res) {
  // P2 fix: /metrics is fail-closed by default. It discloses internal state
  // (uptime, audit/session counts) so it must not be world-readable on a LAN.
  // Enable scraping by setting AEGIS_METRICS_TOKEN and presenting it as
  // `Authorization: Bearer <token>` or `?token=<token>`.
  const tok = process.env.AEGIS_METRICS_TOKEN;
  if (!tok) {
    res.writeHead(401, { 'Content-Type': 'text/plain; charset=utf-8' });
    return res.end('metrics disabled: set AEGIS_METRICS_TOKEN to enable (scrape with Authorization: Bearer <token> or ?token=<token>)');
  }
  const auth = (req.headers.authorization || '').replace(/^Bearer\s+/i, '');
  const q = new URL(req.url, 'http://localhost').searchParams.get('token');
  if (auth !== tok && q !== tok) {
    res.writeHead(401, { 'WWW-Authenticate': 'Bearer', 'Content-Type': 'text/plain; charset=utf-8' });
    return res.end('401 Unauthorized');
  }
  const lines = [
    '# HELP aegis_uptime_seconds Seconds since process start',
    '# TYPE aegis_uptime_seconds counter',
    `aegis_uptime_seconds ${((Date.now() - SERVER_START) / 1000).toFixed(3)}`,
  ];
  try {
    lines.push('# HELP aegis_audit_events_total Total recorded audit events');
    lines.push('# TYPE aegis_audit_events_total counter');
    lines.push(`aegis_audit_events_total ${countEvents()}`);
    lines.push('# HELP aegis_sessions_active Active operator sessions');
    lines.push('# TYPE aegis_sessions_active gauge');
    lines.push(`aegis_sessions_active ${countSessions()}`);
  } catch { /* store not initialised yet */ }
  res.writeHead(200, { 'Content-Type': 'text/plain; version=0.0.4; charset=utf-8' });
  res.end(lines.join('\n') + '\n');
}
