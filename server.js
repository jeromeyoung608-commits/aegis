// Fail fast on a port collision instead of silently leaving a STALE server
// answering requests — the classic EADDRINUSE "ghost process" bug (a leftover
// server from a previous run keeps the port and eats every request while the
// new code fails to bind). Loud exit beats a confusing 404 from old code.
server.on('error', (e) => {
  if (e.code === 'EADDRINUSE') {
    console.error(
      `[FATAL] Port ${PORT} is already in use — a stale server is likely still ` +
      `running. Kill it first, e.g. \`lsof -ti:${PORT} | xargs kill -9\`, ` +
      `then restart this one.`,
    );
    process.exit(1);
  }
  throw e;
});

