function handler(req, res) {
  // Cross-origin isolation — this is NOT an optional nicety and NOT a naive static
  // server. SharedArrayBuffer (used by the WebGPU topology's Worker physics engine)
  // ONLY exists in a cross-origin-isolated context, which requires BOTH of these
  // headers on EVERY response. If we ever served a byte without them, the topology
  // would silently lose SAB and the 10^6-node render would collapse.
  //   • COOP: same-origin  → the page cannot be opened in a cross-origin opener
  //   • COEP: require-corp  → every subresource must be same-origin or explicitly CORP/CORS
  //   • CORP: same-origin   → reinforces that we never leak cross-origin bytes
  // All module assets are served same-origin by this very server, so COEP never blocks
  // them. These headers are set up-front, so static files AND the JSON signaling relay
  // (long-poll) alike are isolated.
  res.setHeader('Cross-Origin-Opener-Policy', 'same-origin');
  res.setHeader('Cross-Origin-Embedder-Policy', 'require-corp');
  res.setHeader('Cross-Origin-Resource-Policy', 'same-origin');
  // v7 P1: close the remaining hardening-header gap. These apply to EVERY
  // response (static + JSON), not just HTML. Aegis uses no device APIs, so a
  // restrictive Permissions-Policy cannot regress the WebGPU/canvas modules
  // (their "camera" is a 3D viewport object, not getUserMedia).
  res.setHeader('Referrer-Policy', 'no-referrer');
  res.setHeader('X-Content-Type-Options', 'nosniff');
  res.setHeader('Permissions-Policy', 'camera=(), microphone=(), geolocation=(), payment=(), usb=()');
  // HSTS is honoured by browsers only over HTTPS; harmless on a plain-HTTP LAN box.
  res.setHeader('Strict-Transport-Security', 'max-age=31536000; includeSubDomains');

  const url = new URL(req.url, 'http://localhost');

  // A2: cap request bodies so an unauthenticated endpoint (e.g. /auth/login) cannot
  // be fed a huge payload to exhaust memory. The compliance upload endpoint is exempt
  // because it carries a base64 document and is legitimately large.
  const clLen = Number(req.headers['content-length'] || 0);
  if (clLen > 1_000_000 && !url.pathname.startsWith('/api/compliance/upload')) {
    res.writeHead(413, { 'Content-Type': 'application/json; charset=utf-8' });
    res.end(JSON.stringify({ error: 'payload too large (max 1 MB)' }));
    req.resume(); // drain the socket so the connection is released cleanly
    return;
  }

  // D1: optional global per-IP rate limit on the API/auth surface (off unless
  // AEGIS_RATE_LIMIT>0). Static + health endpoints are intentionally exempt.
  if (RATE_LIMIT && (url.pathname.startsWith('/api/') || url.pathname.startsWith('/auth/'))) {
    if (globalRateLimited(req.socket.remoteAddress || 'unknown')) { json(res, 429, { error: 'rate limited' }); return; }
  }

  // Public liveness/readiness probe for orchestrators (k8s / Docker / HAProxy).
  // Unauthenticated by design — it reports only aggregate health, never data, so
  // it can sit behind a load balancer without leaking anything.
  if (url.pathname === '/healthz' || url.pathname === '/health') {
    let db = 'ok';
    try { getEvents({ limit: 1 }); } catch { db = 'error'; }
    json(res, 200, { ok: db === 'ok', uptimeSeconds: Math.round(process.uptime()), db, version: VERSION, ts: Date.now() });
    return;
  }
  // Browsers auto-request /favicon.ico; answer 204 so it never logs as a 404.
  if (url.pathname === '/favicon.ico') { res.writeHead(204); res.end(); return; }
  // Exact match only. A naive `pathname.includes('/signal')` also swallows
  // /modules/p2p-crypto-transfer/src/signalers.js (the substring!) and serves it
  // a 400 from the signaling handler instead of the module file.
  if (url.pathname === '/signal' || url.pathname.startsWith('/signal/')) {
    handleSignal(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'signal error' }); });
    return;
  }
  if (url.pathname === '/session') {
    handleSession(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'session error' }); });
    return;
  }
  if (url.pathname === '/adapter/tsa/submit' || url.pathname === '/adapter/tsa/verify') {
    handleTsaSubmit(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'tsa submit error' }); });
    return;
  }
  if (req.method === 'GET' && url.pathname === '/export/bundle') {
    // GDPR Art.20 data-portability export: a self-describing JSON bundle of the audit
    // records a data subject can retrieve. Deliberately excludes any key material,
    // credentials, or file bytes — none of those are server-held.
    if (!operatorAuthorized(req)) {
      json(res, ISSUER_SECRET ? 401 : 503, { error: ISSUER_SECRET ? 'operator credential required' : 'audit locked' });
      return;
    }
    const rows = getEvents({ limit: 10_000 });
    const bundle = {
      product: 'Aegis',
      version: VERSION,
      generatedAt: new Date().toISOString(),
      jurisdictionNote: 'GDPR Art.20 data-portability export — contains audit event records and operator account metadata (username/role/created). Manifests are generated client-side and are not server-held.',
      // Generated-watermark (in-band AEGIS-PROVENANCE): provenance travels with the
      // export so a recipient can prove the bundle originated from AEGIS (Jerome Young)
      // and under which license it was produced.
      provenance: {
        product: 'Aegis',
        version: VERSION,
        author: 'Jerome Young (Yang Jie)',
        copyright: 'Copyright (c) 2026 Jerome Young (Yang Jie). Open source under Apache-2.0.',
        license: 'Apache License 2.0 (Apache-2.0) — see LICENSE. Paid support is optional.',
        generatedBy: 'AEGIS v' + VERSION + ' (Jerome Young)',
      },
      events: rows,
      accounts: listAccounts(),
    };
    res.writeHead(200, { 'Content-Type': 'application/json; charset=utf-8', 'Content-Disposition': 'attachment; filename="aegis-export-bundle.json"' });
    return res.end(JSON.stringify(bundle, null, 2));
  }
  if (url.pathname === '/audit' || url.pathname.startsWith('/audit/')) {
    handleAuditRoute(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'audit error' }); });
    return;
  }
  if (url.pathname === '/relay' || url.pathname.startsWith('/relay/')) {
    handleRelay(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'relay error' }); });
    return;
  }
  if (url.pathname === '/admin/revoke' || url.pathname.startsWith('/admin/revoke')) {
    handleRevocationRoute(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'revocation error' }); });
    return;
  }
  if (url.pathname === '/escrow' || url.pathname.startsWith('/escrow/') || url.pathname === '/escrow/admin') {
    handleEscrowRoute(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'escrow error' }); });
    return;
  }
  if (url.pathname.startsWith('/scim/')) {
    handleScimRoute(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'scim error' }); });
    return;
  }
  if (url.pathname === '/auth/login' || url.pathname === '/auth/logout' || url.pathname === '/auth/me' || url.pathname.startsWith('/auth/oidc') || url.pathname.startsWith('/auth/mfa')) {
    handleAuth(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'auth error' }); });
    return;
  }
  if (url.pathname === '/metrics') { handleMetrics(req, res); return; }
  if (url.pathname === '/api/admin/db-backup') {
    handleBackupRoute(req, res).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'backup error' }); });
    return;
  }
  if (url.pathname.startsWith('/api/compliance')) {
    handleComplianceRoute(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'compliance error' }); });
    return;
  }
  if (url.pathname.startsWith('/api/sessions')) {
    handleSessionsRoute(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'sessions error' }); });
    return;
  }
  if (url.pathname.startsWith('/api/config')) {
    handleConfigRoute(req, res, url).catch((e) => { if (!res.headersSent) json(res, 500, { error: 'config error' }); });
    return;
  }
  // P3 fix: static assets are read-only. Only GET/HEAD may reach the static host;
  // any other method (PUT/POST/DELETE/TRACE) on a static path is rejected with 405
  // rather than silently returning file contents. The request body is never read.
  if (req.method !== 'GET' && req.method !== 'HEAD') {
    res.writeHead(405, { 'Content-Type': 'text/plain; charset=utf-8', 'Allow': 'GET, HEAD' });
    return res.end('405 Method Not Allowed');
  }
  serveStatic(req, res, url);
}

