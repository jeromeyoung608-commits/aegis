// ── Operator-facing deploy configuration (C6) ───────────────────────────────
// Read-only reflection of boot-time config plus a tiny allowlist of safe toggles
// and one safe string (SIEM forward URL) that are persisted to config/local.json
// (applies on restart). Operator-tunable only — never the issuer secret.
const CONFIG_SAFE_TOGGLES = ['escrow.requireForAdmit', 'auth.mfaEnforced'];
const CONFIG_SAFE_STRINGS = ['audit.forwardUrl'];
async function handleConfigRoute(req, res, url) {
  if (!operatorAuthorized(req)) {
    json(res, ISSUER_SECRET ? 401 : 503, { error: ISSUER_SECRET ? 'operator credential required' : 'config locked' });
    return;
  }
  if (req.method === 'GET' && url.pathname === '/api/config') {
    return json(res, 200, {
      authMode: CONFIG.auth.mode,
      oidcConfigured: !!(CONFIG.auth.oidc && CONFIG.auth.oidc.issuer),
      escrowEnabled: !!(CONFIG.escrow && CONFIG.escrow.enabled),
      escrowRequireForAdmit: !!(CONFIG.escrow && CONFIG.escrow.requireForAdmit),
      rtcIceServers: (CONFIG.rtc && Array.isArray(CONFIG.rtc.iceServers)) ? CONFIG.rtc.iceServers.length : 0,
      mfaEnforced: !!(CONFIG.auth && CONFIG.auth.mfaEnforced),
      tsaMode: (CONFIG.tsa && CONFIG.tsa.mode) || 'off',
      auditForwardUrl: (CONFIG.audit && CONFIG.audit.forwardUrl) || '',
    });
  }
  if (req.method === 'PUT' && url.pathname === '/api/config') {
    const body = await readJsonBody(req);
    if (!body || typeof body !== 'object' || Array.isArray(body)) { json(res, 400, { error: 'object required' }); return; }
    const cur = (() => { try { return JSON.parse(fs.readFileSync(path.join(ROOT, 'config', 'local.json'), 'utf8')); } catch { return {}; } })();
    for (const key of CONFIG_SAFE_TOGGLES) {
      if (Object.prototype.hasOwnProperty.call(body, key)) {
        const [a, b] = key.split('.');
        cur[a] = cur[a] || {}; cur[a][b] = !!body[key];
      }
    }
    for (const key of CONFIG_SAFE_STRINGS) {
      if (Object.prototype.hasOwnProperty.call(body, key)) {
        const v = String(body[key] || '').trim();
        if (v) { cur.audit = cur.audit || {}; cur.audit.forwardUrl = v; }
        else if (cur.audit) { delete cur.audit.forwardUrl; }
        setAuditForwardUrl(v);
      }
    }
    fs.mkdirSync(path.join(ROOT, 'config'), { recursive: true });
    fs.writeFileSync(path.join(ROOT, 'config', 'local.json'), JSON.stringify(cur, null, 2));
    recordAudit({ kind: 'config.updated', subject: 'operator', detail: 'config override written (applies on restart)' });
    return json(res, 200, { ok: true, note: 'changes apply on next restart' });
  }
  json(res, 404, { error: 'not found' });
}

