function isPublicPath(filePath) {
  const rel = path.relative(ROOT, filePath);
  if (!rel || rel.startsWith('..') || path.isAbsolute(rel)) return false;
  const parts = rel.split(path.sep);
  if (DENY_TOP_LEVEL.has(parts[0])) return false;
  if (parts.some((seg) => seg.startsWith('.') || DENY_DIRS.has(seg))) return false;
  if (DENY_BASENAMES.has(parts[parts.length - 1])) return false;
  if (DENY_EXTS.has(path.extname(filePath).toLowerCase())) return false;
  return true;
}

