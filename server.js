const loginIpUsers = new Map();
// OIDC: in-flight authorization requests (state -> nonce) with a short TTL, so the
// callback can bind the response to the request and check the replay nonce.
const oidcStates = new Map();
const OIDC_STATE_TTL = 5 * 60 * 1000;
const LOGIN_ENUM_DISTINCT = 8;
function loginEnumHit(ip, username) {
  const now = Date.now();
  let r = loginIpUsers.get(ip);
  if (!r || now > r.reset) { r = { users: new Set([username]), reset: now + LOGIN_USER_WINDOW }; loginIpUsers.set(ip, r); }
  else r.users.add(username);
  return r.users.size > LOGIN_ENUM_DISTINCT;
}
function loginHit(map, key, max, window) {
  const now = Date.now();
  let r = map.get(key);
  if (!r || now > r.reset) { r = { count: 0, reset: now + window }; map.set(key, r); }
  r.count += 1;
  return r.count > max;
}
