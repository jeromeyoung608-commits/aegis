// Cheap per-IP rate limit on the signaling relay (defeats room-name spraying / DoS).
const RATE = new Map();
const RATE_MAX = 60;          // requests per window
const RATE_WINDOW = 60_000;   // 1 minute
function rateLimited(ip) {
  const now = Date.now();
  let r = RATE.get(ip);
  if (!r || now > r.reset) { r = { count: 0, reset: now + RATE_WINDOW }; RATE.set(ip, r); }
  r.count += 1;
  return r.count > RATE_MAX;
}

